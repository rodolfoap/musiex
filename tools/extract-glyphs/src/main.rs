//! Extracts the SMuFL glyphs musiex draws from Bravura.otf as SVG path data
//! in staff spaces (y pointing down, origin at the glyph origin).
//!
//! Usage: cargo run --manifest-path tools/extract-glyphs/Cargo.toml -- Bravura.otf > crates/musiex-engrave/src/glyphs.rs
//!
//! Bravura is © Steinberg Media Technologies GmbH, under the SIL Open Font
//! License 1.1 (see crates/musiex-engrave/BRAVURA-OFL.txt).

use std::fmt::Write;
use ttf_parser::{Face, GlyphId, OutlineBuilder};

const GLYPHS: &[(&str, u32)] = &[
    ("G_CLEF", 0xE050),
    ("C_CLEF", 0xE05C),
    ("F_CLEF", 0xE062),
    ("TIME_SIG_0", 0xE080),
    ("TIME_SIG_1", 0xE081),
    ("TIME_SIG_2", 0xE082),
    ("TIME_SIG_3", 0xE083),
    ("TIME_SIG_4", 0xE084),
    ("TIME_SIG_5", 0xE085),
    ("TIME_SIG_6", 0xE086),
    ("TIME_SIG_7", 0xE087),
    ("TIME_SIG_8", 0xE088),
    ("TIME_SIG_9", 0xE089),
    ("NOTEHEAD_WHOLE", 0xE0A2),
    ("NOTEHEAD_HALF", 0xE0A3),
    ("NOTEHEAD_BLACK", 0xE0A4),
    ("AUGMENTATION_DOT", 0xE1E7),
    ("FLAG_8TH_UP", 0xE240),
    ("FLAG_8TH_DOWN", 0xE241),
    ("FLAG_16TH_UP", 0xE242),
    ("FLAG_16TH_DOWN", 0xE243),
    ("ACCIDENTAL_FLAT", 0xE260),
    ("ACCIDENTAL_NATURAL", 0xE261),
    ("ACCIDENTAL_SHARP", 0xE262),
    ("REST_WHOLE", 0xE4E3),
    ("REST_HALF", 0xE4E4),
    ("REST_QUARTER", 0xE4E5),
    ("REST_8TH", 0xE4E6),
    ("REST_16TH", 0xE4E7),
    ("TUPLET_3", 0xE883),
];

struct Path {
    d: String,
    scale: f32,
}

impl Path {
    fn pt(&mut self, x: f32, y: f32) {
        let _ = write!(self.d, "{:.3} {:.3}", x * self.scale, -y * self.scale);
    }
}

impl OutlineBuilder for Path {
    fn move_to(&mut self, x: f32, y: f32) {
        self.d.push('M');
        self.pt(x, y);
    }
    fn line_to(&mut self, x: f32, y: f32) {
        self.d.push('L');
        self.pt(x, y);
    }
    fn quad_to(&mut self, x1: f32, y1: f32, x: f32, y: f32) {
        self.d.push('Q');
        self.pt(x1, y1);
        self.d.push(' ');
        self.pt(x, y);
    }
    fn curve_to(&mut self, x1: f32, y1: f32, x2: f32, y2: f32, x: f32, y: f32) {
        self.d.push('C');
        self.pt(x1, y1);
        self.d.push(' ');
        self.pt(x2, y2);
        self.d.push(' ');
        self.pt(x, y);
    }
    fn close(&mut self) {
        self.d.push('Z');
    }
}

fn main() {
    let path = std::env::args().nth(1).expect("usage: extract-glyphs Bravura.otf");
    let data = std::fs::read(&path).expect("reading the font");
    let face = Face::parse(&data, 0).expect("parsing the font");
    // SMuFL: one staff space is a quarter of the em.
    let scale = 4.0 / f32::from(face.units_per_em());

    println!("//! Generated by tools/extract-glyphs from Bravura (SIL Open Font License 1.1).");
    println!("//! Do not edit by hand. Units are staff spaces, y down.");
    println!();
    println!("use crate::Glyph;");
    for &(name, cp) in GLYPHS {
        let ch = char::from_u32(cp).unwrap();
        let id: GlyphId = face.glyph_index(ch).unwrap_or_else(|| panic!("{name} missing"));
        let mut p = Path {
            d: String::new(),
            scale,
        };
        let bbox = face.outline_glyph(id, &mut p).expect("glyph has an outline");
        let advance = f32::from(face.glyph_hor_advance(id).unwrap_or(0)) * scale;
        println!();
        println!("pub const {name}: Glyph = Glyph {{");
        println!("    path: \"{}\",", p.d);
        println!(
            "    // x_min, y_min, x_max, y_max (y down)\n    bbox: ({:.3}, {:.3}, {:.3}, {:.3}),",
            f32::from(bbox.x_min) * scale,
            -f32::from(bbox.y_max) * scale,
            f32::from(bbox.x_max) * scale,
            -f32::from(bbox.y_min) * scale
        );
        println!("    advance: {advance:.3},");
        println!("}};");
    }
}
