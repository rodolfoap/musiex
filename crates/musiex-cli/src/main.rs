//! `musiex`: generate sight-reading exercises from the command line.

mod midi;

use anyhow::{Context, Result};
use clap::{Args, Parser, Subcommand};
use musiex_core::{abc, Clef, Generator, Key, Meter, Pitch, Settings};
use std::path::PathBuf;

#[derive(Parser)]
#[command(name = "musiex", version, about = "Endless sight-reading exercises")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Write an exercise as ABC notation and a MIDI file.
    Generate(GenerateArgs),
}

#[derive(Args)]
struct GenerateArgs {
    /// Number of bars to write.
    #[arg(short = 'n', long, default_value_t = 32)]
    bars: usize,

    /// Output path without extension; writes PATH.abc and PATH.mid.
    #[arg(short, long, default_value = "exercise")]
    output: PathBuf,

    /// Only write the ABC file.
    #[arg(long)]
    abc_only: bool,

    #[command(flatten)]
    music: MusicArgs,

    /// Title printed on the score.
    #[arg(short = 'T', long, default_value = "Sight-reading exercise")]
    title: String,

    /// Composer line on the score.
    #[arg(short = 'C', long)]
    composer: Option<String>,

    /// Leave the metronome click out of the MIDI file.
    #[arg(long)]
    no_metronome: bool,

    /// Bars of metronome before the music starts.
    #[arg(long, default_value_t = 1)]
    count_in: u32,
}

#[derive(Args)]
struct MusicArgs {
    /// Beats per minute; in 6/8 the beat is a dotted quarter.
    #[arg(short, long, default_value_t = 60)]
    tempo: u32,

    /// Time signature, e.g. 4/4, 3/4, 6/8, 5/4.
    #[arg(short, long, default_value = "4/4")]
    meter: Meter,

    /// Key, e.g. C, G, Bb, F#m.
    #[arg(short, long, default_value = "C")]
    key: Key,

    /// Clef: treble, bass, alto or tenor.
    #[arg(short, long, default_value = "treble")]
    clef: Clef,

    /// Note range as LOW..HIGH, e.g. C4..A5. Defaults to a comfortable range for the clef.
    #[arg(short, long, value_parser = parse_range)]
    range: Option<(Pitch, Pitch)>,

    /// Smallest note value: 1 halves, 2 quarters, 3 eighths, 4 sixteenths.
    #[arg(short, long, default_value_t = 2, value_parser = clap::value_parser!(u8).range(1..=4))]
    level: u8,

    /// Largest jump between notes, in staff steps (2 is a third).
    #[arg(short = 'd', long = "leap", default_value_t = 3)]
    max_leap: u8,

    /// Include rests.
    #[arg(long)]
    rests: bool,

    /// Include triplets.
    #[arg(long)]
    triplets: bool,

    /// Include dotted pairs (dotted eighth plus sixteenth, and so on).
    #[arg(long)]
    dotted: bool,

    /// Include ties.
    #[arg(long, alias = "legato")]
    ties: bool,

    /// Include accidental sharps.
    #[arg(long)]
    sharps: bool,

    /// Include accidental flats.
    #[arg(long)]
    flats: bool,

    /// Seed for a reproducible exercise. A random one is picked and printed if omitted.
    #[arg(short, long)]
    seed: Option<u64>,
}

fn parse_range(s: &str) -> Result<(Pitch, Pitch), String> {
    let (lo, hi) = s
        .split_once("..")
        .ok_or_else(|| format!("invalid range '{s}', expected LOW..HIGH such as C4..A5"))?;
    let lo: Pitch = lo.parse().map_err(|e| format!("{e}"))?;
    let hi: Pitch = hi.parse().map_err(|e| format!("{e}"))?;
    Ok((lo, hi))
}

fn random_seed() -> u64 {
    use std::time::{SystemTime, UNIX_EPOCH};
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or_default();
    // Keep seeds short enough to type back in.
    (nanos % 1_000_000) as u64
}

impl MusicArgs {
    fn settings(&self) -> Settings {
        let (low, high) = self.range.unwrap_or_else(|| self.clef.default_range());
        Settings {
            meter: self.meter,
            key: self.key,
            clef: self.clef,
            tempo: self.tempo,
            low,
            high,
            level: self.level,
            max_leap: self.max_leap,
            rests: self.rests,
            triplets: self.triplets,
            dotted: self.dotted,
            ties: self.ties,
            sharps: self.sharps,
            flats: self.flats,
            seed: self.seed.unwrap_or_else(random_seed),
        }
    }
}

fn with_extension(base: &std::path::Path, ext: &str) -> PathBuf {
    let mut name = base.as_os_str().to_owned();
    name.push(".");
    name.push(ext);
    PathBuf::from(name)
}

fn generate(args: &GenerateArgs) -> Result<()> {
    let settings = args.music.settings();
    let generator = Generator::new(settings.clone())?;
    let bars: Vec<_> = generator.take(args.bars.max(1)).collect();

    let header = abc::Header {
        title: args.title.clone(),
        composer: args.composer.clone(),
        notes: Some(format!("Generated by musiex, seed {}", settings.seed)),
    };
    let abc_path = with_extension(&args.output, "abc");
    std::fs::write(&abc_path, abc::tune(&settings, &header, &bars, 4))
        .with_context(|| format!("writing {}", abc_path.display()))?;
    println!("wrote {}", abc_path.display());

    if !args.abc_only {
        let mid_path = with_extension(&args.output, "mid");
        let bytes = midi::write(&settings, &bars, !args.no_metronome, args.count_in)?;
        std::fs::write(&mid_path, bytes)
            .with_context(|| format!("writing {}", mid_path.display()))?;
        println!("wrote {}", mid_path.display());
    }
    println!("seed {}", settings.seed);
    Ok(())
}

fn main() -> Result<()> {
    match Cli::parse().command {
        Command::Generate(args) => generate(&args),
    }
}
